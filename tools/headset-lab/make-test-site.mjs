function walk(dir) {
  let n = 0, bytes = 0;
  for (const f of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, f.name);
    if (f.isDirectory()) { const r = walk(p); n += r.n; bytes += r.bytes; } else { n++; bytes += statSync(p).size; }
  }
  return { n, bytes };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { GROUPS } = await import(pathToFileURL(join(HERE, 'hub/tests.js')).href);
  const frame = parseFrameSteps(readFileSync(GODOT_DOC, 'utf8'));
  const noApps = process.argv.includes('--no-apps');
  if (!noApps) {
    rmSync(OUT, { recursive: true, force: true }); mkdirSync(OUT, { recursive: true });
    for (const [name, src] of APPS) {
      if (!existsSync(join(src, 'index.html'))) throw new Error(`Missing ${src}/index.html: build it first (README, "Testsite")`);
      cpSync(src, join(OUT, name), { recursive: true });
    }
    rmSync(join(OUT, 'contracts', 'MANIFEST.json'), { force: true });
  } else mkdirSync(OUT, { recursive: true });
  // Every link must point at a built page.
  const missing = [];
  if (!noApps) for (const g of GROUPS) for (const t of g.tests) for (const [, href] of t.links) {
    const path = rel(href).split('?')[0];
    if (!existsSync(join(OUT, path.endsWith('/') ? path + 'index.html' : path))) missing.push(`${t.id}: ${href}`);
  }
  if (missing.length) throw new Error('Links without a built page:\n' + missing.join('\n'));
  writeFileSync(join(OUT, 'index.html'), renderPage(GROUPS, frame));
  const { n, bytes } = walk(OUT);
  console.log(`Built ${n} files (${(bytes / 1048576).toFixed(1)} MB) in ${OUT}; ${GROUPS.reduce((a, g) => a + g.tests.length, 0)} tests, ${frame.steps.length} Frame steps.`);
}
