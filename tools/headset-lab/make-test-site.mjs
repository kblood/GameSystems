export function parseFrameSteps(markdown) {
  const lines = markdown.split(/\r?\n/);
  const start = lines.findIndex(l => /\*\*Tjek på Frame\/Quest\*\*/.test(l));
  if (start < 0) throw new Error('"Tjek på Frame/Quest" not found in ' + GODOT_DOC);
  const header = lines[start].replace(/\*\*/g, '').replace(/[:\s]+$/, '').trim();
  const steps = [];
  for (const l of lines.slice(start + 1)) {
    const m = /^\s*\d+\.\s+(.*\S)\s*$/.exec(l);
    if (m) steps.push(m[1].replace(/^Tjek på Frame\/Quest:\s*/, ''));
    else if (steps.length) break;
  }
  return { header, steps };
}

