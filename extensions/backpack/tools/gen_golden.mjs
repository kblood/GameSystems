// Generates data/backpack.golden.json from tools/vectors.mjs (inputs) by running the JS core (the source of the numbers),
// and copies the contract files into the Godot addon so GDScript reads the same bytes.
//   node extensions/backpack/tools/gen_golden.mjs          write golden + Godot copies
//   node extensions/backpack/tools/gen_golden.mjs --check  exit 1 when a file is missing or out of date (writes nothing)
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { approachVectors, pullVectors, stateVectors, profileCases } from './vectors.mjs';
import { runApproach, runPull, runState, runProfile, GOLDEN_SCHEMA } from './golden_runner.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
export const DATA_DIR = resolve(HERE, '../data');
export const ROOT = resolve(HERE, '../../..');
export const GODOT_DATA_DIR = resolve(ROOT, 'godot/addons/gs_backpack/data');
export const COPIED = ['backpack.data.json', 'profile.example.json', 'backpack.golden.json'];

export async function buildGolden() {
  const profile = JSON.parse(await readFile(resolve(DATA_DIR, 'profile.example.json'), 'utf8'));
  const files = { profiles: { example: profile } };
  return {
    schema: GOLDEN_SCHEMA,
    note: 'Generated by extensions/backpack/tools/gen_golden.mjs from tools/vectors.mjs. Do not edit by hand. Non-finite numbers are "NaN"/"Infinity".',
    profiles: { example: profile },
    profileCases: profileCases(profile).map(v => ({ ...v, expected: runProfile(v) })),
    approach: approachVectors.map(v => ({ ...v, expected: runApproach(v) })),
    pull: pullVectors.map(v => ({ ...v, expected: runPull(v) })),
    state: stateVectors.map(v => ({ ...v, expected: runState(v, files) })),
  };
}

// One line per op / expected row keeps the file reviewable and small.
const line = v => JSON.stringify(v);
export function goldenText(g) {
  const vec = v => '{' + Object.entries(v).map(([k, x]) => (k === 'ops' || k === 'expected'
    ? `"${k}":[\n${x.map(line).map(s => '   ' + s).join(',\n')}\n  ]` : `"${k}":${line(x)}`)).join(',\n  ') + '}';
  const list = arr => '[\n' + arr.map(vec).map(s => ' ' + s).join(',\n') + '\n]';
  return '{' + ['schema', 'note', 'profiles'].map(k => `"${k}":${line(g[k])}`).join(',\n')
    + `,\n"profileCases":[\n${g.profileCases.map(v => ' ' + line(v)).join(',\n')}\n]`
    + `,\n"approach":${list(g.approach)},\n"pull":${list(g.pull)},\n"state":${list(g.state)}\n}\n`;
}

async function main() {
  const check = process.argv.includes('--check');
  const rel = p => relative(ROOT, p).split('\\').join('/');
  const golden = goldenText(await buildGolden());
  const targets = [{ path: resolve(DATA_DIR, 'backpack.golden.json'), content: golden }];
  for (const name of COPIED) {
    const content = name === 'backpack.golden.json' ? golden : await readFile(resolve(DATA_DIR, name), 'utf8');
    targets.push({ path: resolve(GODOT_DATA_DIR, name), content });
  }
  const stale = [];
  for (const t of targets) {
    let current = null;
    try { current = await readFile(t.path, 'utf8'); } catch { /* missing */ }
    if (current === t.content) continue;
    stale.push(rel(t.path));
    if (!check) { await mkdir(dirname(t.path), { recursive: true }); await writeFile(t.path, t.content); }
  }
  if (check && stale.length) { console.error(`out of date: ${stale.join(', ')}`); process.exit(1); }
  console.log(check ? 'backpack golden files are current' : `wrote ${stale.length ? stale.join(', ') : 'nothing (already current)'}`);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
