#!/usr/bin/env node
// Read-only sync gate across the projects that carry copies of GameSystems code (extension F20 in docs/improvement_proposals.md).
// It writes nothing (except the optional --json report), runs no sync and is wired into no hook or CI. Usage:
//   node scripts/check_sync.mjs [--json report.json] [--no-baseline] [--strict-stamp] [--quiet]
//   env: CONTRACTS_DIR, NIGHTFALL_GODOT_DIR (default: sibling folders of GameSystems)
//
// Units checked (hash comparison after CRLF -> LF for text files, raw bytes for binaries):
//   contracts/<ext>        NightfallContractsWebXR-interaction/src/extensions/<ext> against GameSystems/extensions/<ext>
//                          and its SYNCED.json (same file rules as that repo's tools/sync_extensions.mjs, which compares raw bytes).
//   contracts/assets       assets/gamesystems/SYNCED.json (bottle GLB/LUT/OGG subset) against the files and GameSystems.
//   webxr-demo/<ext>       webxr-demo/src/vendor/extensions/<ext> (no manifest; generated by npm run sync = mirror of GameSystems).
//   grasp-studio/<ext>     apps/grasp-studio/src/vendor/extensions/<ext> (same).
//   nightfall-godot/<addon> NightfallContractsGodot/addons/<addon> against its SOURCE.json and godot/addons/<addon>.
// Per file: equal | crlf-only (equal after normalisation, raw bytes differ) | behind (source changed since the sync) |
// edited (copy changed locally) | diverged (both) | missing (in copy) | extra (only in copy). Declared local adaptations
// (SOURCE.json local_adaptations) are reported as intentional and never fail the gate. A SYNCED.json commit stamp that
// is not GameSystems HEAD is only informational (the hashes are what matter) unless --strict-stamp.
// Known, accepted drift lives in scripts/check_sync.baseline.json ({unit: {files: [...], reason}}); drift outside it is
// UNEXPECTED and gives exit code 1. Extensions/addons a project deliberately does not carry are reported as not-vendored.
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { join, resolve, dirname, extname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const GS = resolve(here, '..');
const dev = resolve(GS, '..');
const CONTRACTS = resolve(process.env.CONTRACTS_DIR || join(dev, 'NightfallContractsWebXR-interaction'));
const NIGHTFALL = resolve(process.env.NIGHTFALL_GODOT_DIR || join(dev, 'NightfallContractsGodot'));
const args = process.argv.slice(2);
const flag = n => args.includes(n);
const jsonOut = args.includes('--json') ? args[args.indexOf('--json') + 1] : null;
const TEXT = new Set(['.gd', '.json', '.md', '.txt', '.cfg', '.gdshader', '.gdshaderinc', '.tscn', '.tres', '.csv', '.js', '.mjs', '.html', '.css', '.glsl', '']);
const IGNORED = new Set(['.uid', '.import']);

const raw = p => readFileSync(p);
const sha = b => createHash('sha256').update(b).digest('hex');
const norm = (p, b) => (TEXT.has(extname(p).toLowerCase()) ? Buffer.from(b.toString('latin1').replace(/\r\n/g, '\n'), 'latin1') : b);
const hashes = p => { const b = raw(p); return { raw: sha(b), norm: sha(norm(p, b)) }; };
const walk = (dir, base = '') => {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const rel = base ? `${base}/${e.name}` : e.name;
    if (e.isDirectory()) { if (e.name !== '__pycache__' && e.name !== 'node_modules') out.push(...walk(join(dir, e.name), rel)); } else out.push(rel);
  }
  return out;
};
const top = dir => readdirSync(dir, { withFileTypes: true }).filter(e => e.isFile()).map(e => e.name);
const git = (...a) => { try { return execFileSync('git', ['-C', GS, ...a], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim(); } catch { return ''; } };
const headShort = git('rev-parse', '--short', 'HEAD');
const baseline = flag('--no-baseline') || !existsSync(join(here, 'check_sync.baseline.json')) ? {} : JSON.parse(readFileSync(join(here, 'check_sync.baseline.json'), 'utf8'));

// Which source files an extension syncs: top-level files plus the data subfolders of sync_lib.mjs / sync_extensions.mjs.
const SYNC_SUBDIRS = { grasp: ['data'], gore: ['data'], backpack: ['data'], furniture: ['data'] };
const GENERATED = { 'character-cc': ['vendor', 'assets'] };
const extSource = name => {
  const dir = join(GS, 'extensions', name);
  const files = top(dir);
  for (const s of SYNC_SUBDIRS[name] ?? []) if (existsSync(join(dir, s))) files.push(...walk(join(dir, s), s));
  return files.sort();
};
const isGenerated = (name, rel) => (GENERATED[name] ?? []).some(g => rel === g || rel.startsWith(g + '/'));

const units = [];
/** Add a unit; entries: [{file, state, note?}] with state in equal|crlf-only|behind|edited|diverged|missing|extra|intentional. */
function addUnit(project, name, entries, extra = {}) {
  const bad = entries.filter(e => !['equal', 'crlf-only', 'intentional'].includes(e.state));
  const key = `${project}/${name}`;
  const known = baseline[key];
  const knownFiles = new Set(known?.files ?? []);
  const unexpected = bad.filter(e => !(known && (!known.files || knownFiles.has(e.file))));
  const status = bad.length === 0 ? 'SYNCED' : unexpected.length ? 'DRIFT' : 'KNOWN-DRIFT';
  units.push({ project, name, files: entries.length, equal: entries.filter(e => e.state === 'equal').length,
    crlfOnly: entries.filter(e => e.state === 'crlf-only').length, intentional: entries.filter(e => e.state === 'intentional').length,
    drift: bad.length, status, baselineReason: known?.reason, entries: entries.filter(e => e.state !== 'equal'), ...extra });
}
const infoUnits = [];
const info = (project, name, status, note) => infoUnits.push({ project, name, status, note });

/** Classify one file given source hash, copy hash and (optional) the hash the manifest recorded at sync time. */
function classify(srcH, tgtH, recorded) {
  if (!tgtH) return 'missing';
  if (!srcH) return 'extra';
  if (srcH.norm === tgtH.norm) return srcH.raw === tgtH.raw ? 'equal' : 'crlf-only';
  if (!recorded) return 'diverged';
  const matches = h => h.raw === recorded || h.norm === recorded;
  if (matches(tgtH)) return 'behind';
  if (matches(srcH)) return 'edited';
  return 'diverged';
}
const readJson = p => JSON.parse(readFileSync(p, 'utf8'));

// ---- Contracts (web) ------------------------------------------------------------------------------------------------
if (existsSync(join(CONTRACTS, 'src/extensions'))) {
  let wired = null;
  try { wired = (await import(pathToFileURL(join(CONTRACTS, 'tools/sync_extensions.mjs')).href)).EXTENSIONS; } catch { /* fall through */ }
  const present = readdirSync(join(CONTRACTS, 'src/extensions'), { withFileTypes: true }).filter(e => e.isDirectory()).map(e => e.name);
  for (const name of (wired ?? present).filter(n => existsSync(join(GS, 'extensions', n)))) {
    const to = join(CONTRACTS, 'src/extensions', name);
    const synced = existsSync(join(to, 'SYNCED.json')) ? readJson(join(to, 'SYNCED.json')) : null;
    const src = extSource(name);
    const have = existsSync(to) ? top(to).filter(f => f !== 'SYNCED.json').concat(...(SYNC_SUBDIRS[name] ?? []).filter(s => existsSync(join(to, s))).map(s => walk(join(to, s), s))) : [];
    const entries = [];
    for (const f of new Set([...src, ...have])) {
      if (isGenerated(name, f)) continue;
      const s = src.includes(f) ? hashes(join(GS, 'extensions', name, f)) : null;
      const t = have.includes(f) ? hashes(join(to, f)) : null;
      entries.push({ file: f, state: classify(s, t, synced?.files?.[f]) });
    }
    const stamp = synced?.gameSystemsCommit ?? null;
    const behind = stamp && headShort && stamp !== headShort ? git('rev-list', '--count', `${stamp}..HEAD`, '--', `extensions/${name}`) : null;
    if (!synced) entries.push({ file: 'SYNCED.json', state: 'missing' });
    else if (flag('--strict-stamp') && stamp !== headShort) entries.push({ file: 'SYNCED.json', state: 'behind', note: `commit stamp ${stamp} != HEAD ${headShort}` });
    addUnit('contracts', name, entries, { stamp, headStamp: headShort, stampBehind: stamp !== headShort, extensionCommitsSinceStamp: behind === null || behind === '' ? null : Number(behind) });
  }
  const carried = new Set(wired ?? present);
  const skipped = readdirSync(join(GS, 'extensions'), { withFileTypes: true }).filter(e => e.isDirectory() && !carried.has(e.name) && existsSync(join(GS, 'extensions', e.name, 'index.js'))).map(e => e.name);
  info('contracts', 'not-vendored', 'info', `${skipped.length} GameSystems extensions are not copied by Contracts' sync_extensions.mjs: ${skipped.join(', ')}`);
  // Bottle/audio asset subset and the other generated manifests.
  const assetDir = join(CONTRACTS, 'assets/gamesystems');
  if (existsSync(join(assetDir, 'SYNCED.json'))) {
    const m = readJson(join(assetDir, 'SYNCED.json')), entries = [];
    for (const [rel, h] of Object.entries(m.files)) {
      const t = existsSync(join(assetDir, rel)) ? hashes(join(assetDir, rel)) : null;
      const sp = join(GS, rel), s = rel === 'catalog.json' ? t : existsSync(sp) ? hashes(sp) : null;
      entries.push({ file: rel, state: classify(s, t, h) });
    }
    for (const rel of walk(assetDir)) if (rel !== 'SYNCED.json' && !(rel in m.files)) entries.push({ file: rel, state: 'extra' });
    addUnit('contracts', 'assets/gamesystems', entries);
    const sounds = readJson(join(GS, 'extensions/audio/sound_materials.json'));
    const shipped = Object.keys(m.files).filter(f => f.startsWith('audio/ogg/')).length;
    const all = Object.values(sounds.sounds).reduce((n, s) => n + s.variants, 0);
    info('contracts', 'audio assets', 'info', `ships ${shipped} of ${all} GameSystems sound variants (AUDIO_GROUPS subset in tools/sync_extensions.mjs); extension code is complete`);
  }
  for (const rel of ['assets/weapons', 'src/extensions/character-cc/vendor/cc']) {
    const dir = join(CONTRACTS, rel);
    if (!existsSync(join(dir, 'SYNCED.json'))) continue;
    const m = readJson(join(dir, 'SYNCED.json')), entries = [];
    // assets/weapons: {rel: sha} relative to its folder; character-cc/vendor/cc: [{file, sha256}] relative to the Contracts root.
    const list = Array.isArray(m.files) ? m.files.map(x => [join(CONTRACTS, x.file), x.sha256, x.file]) : Object.entries(m.files ?? {}).map(([f, h]) => [join(dir, f), h, f]);
    for (const [path, h, f] of list) {
      const t = existsSync(path) ? hashes(path) : null;
      entries.push({ file: f, state: !t ? 'missing' : t.raw === h || t.norm === h ? 'equal' : 'edited' });
    }
    addUnit('contracts', `${rel} (self-integrity)`, entries);
  }
} else info('contracts', '-', 'missing', `${CONTRACTS}/src/extensions not found`);

// ---- GameSystems apps with generated vendor folders --------------------------------------------------------------------
function appVendor(project, appDir, scriptFile) {
  const script = join(GS, appDir, scriptFile), vendor = join(GS, appDir, 'src/vendor/extensions');
  if (!existsSync(script) || !existsSync(vendor)) return info(project, '-', 'missing', `${appDir} vendor not found`);
  const list = /const EXTENSIONS = \[([\s\S]*?)\];/.exec(readFileSync(script, 'utf8'))?.[1].match(/'([^']+)'/g)?.map(s => s.slice(1, -1)) ?? [];
  for (const name of list) {
    if (name === 'character-vrm') { /* assets fetched separately; code still mirrored below */ }
    const to = join(vendor, name);
    if (!existsSync(to)) { addUnit(project, name, [{ file: '(whole extension)', state: 'missing' }]); continue; }
    const src = extSource(name);
    const have = walk(to).filter(f => !isGenerated(name, f));
    const entries = [];
    for (const f of new Set([...src, ...have])) {
      const s = src.includes(f) ? hashes(join(GS, 'extensions', name, f)) : null;
      const t = have.includes(f) ? hashes(join(to, f)) : null;
      entries.push({ file: f, state: classify(s, t, null) });
    }
    addUnit(project, name, entries);
  }
  const stale = readdirSync(vendor, { withFileTypes: true }).filter(e => e.isDirectory() && !list.includes(e.name)).map(e => e.name);
  if (stale.length) info(project, 'stale folders', 'warn', `vendor/extensions has folders not in the sync list: ${stale.join(', ')}`);
  // character-cc/vendor/cc is generated from Contracts, not from GameSystems.
  const cc = join(vendor, 'character-cc/vendor/cc'), from = join(CONTRACTS, 'src/extensions/character-cc/vendor/cc');
  if (existsSync(cc) && existsSync(from)) {
    const entries = [];
    const a = walk(from), b = walk(cc);
    for (const f of new Set([...a, ...b])) entries.push({ file: f, state: classify(a.includes(f) ? hashes(join(from, f)) : null, b.includes(f) ? hashes(join(cc, f)) : null, null) });
    addUnit(project, 'character-cc/vendor/cc (from Contracts)', entries);
  }
}
appVendor('webxr-demo', 'webxr-demo', 'scripts/sync-helpers.mjs');
appVendor('grasp-studio', 'apps/grasp-studio', 'scripts/sync.mjs');

// ---- Nightfall Godot addons -------------------------------------------------------------------------------------------
if (existsSync(join(NIGHTFALL, 'addons'))) {
  const gsAddons = readdirSync(join(GS, 'godot/addons'), { withFileTypes: true }).filter(e => e.isDirectory() && e.name.startsWith('gs_')).map(e => e.name);
  const ignore = rel => IGNORED.has(extname(rel)) || rel.split('/').includes('__pycache__') || rel === 'SOURCE.json';
  const copies = readdirSync(join(NIGHTFALL, 'addons'), { withFileTypes: true }).filter(e => e.isDirectory() && existsSync(join(NIGHTFALL, 'addons', e.name, 'SOURCE.json'))).map(e => e.name);
  for (const name of copies) {
    const dir = join(NIGHTFALL, 'addons', name), m = readJson(join(dir, 'SOURCE.json'));
    // local_adaptations: objects {target, note} name files; plain strings are prose notes about files the manifest owns.
    const adapt = new Map((m.local_adaptations ?? []).filter(a => typeof a !== 'string').map(a => [a.target, a.note]));
    const prose = (m.local_adaptations ?? []).filter(a => typeof a === 'string');
    const entries = [], seen = new Set();
    for (const f of m.files ?? []) {
      const target = f.target.replaceAll('\\', '/'), source = f.source.replaceAll('\\', '/');
      seen.add(target);
      const tp = join(NIGHTFALL, target), sp = join(GS, source);
      entries.push({ file: target, state: classify(existsSync(sp) ? hashes(sp) : null, existsSync(tp) ? hashes(tp) : null, f.sha256) });
    }
    // Declared local adaptations (and hand-copied files) that the manifest does not list.
    for (const [target, note] of adapt) {
      if (typeof target !== 'string' || seen.has(target)) continue;
      seen.add(target);
      const tp = join(NIGHTFALL, target), rel = target.replace(`addons/${name}/`, '');
      const sp = join(GS, 'godot/addons', name, rel);
      const same = existsSync(tp) && existsSync(sp) && hashes(tp).norm === hashes(sp).norm;
      entries.push({ file: target, state: existsSync(tp) ? 'intentional' : 'missing', note: `${note}${same ? ' [identical to source]' : ' [differs from source]'}` });
    }
    if (name !== 'game_systems') {
      const srcRoot = join(GS, 'godot/addons', name);
      if (existsSync(srcRoot)) for (const rel of walk(srcRoot)) {
        const target = `addons/${name}/${rel}`;
        if (ignore(rel) || seen.has(target)) continue;
        entries.push({ file: target, state: existsSync(join(NIGHTFALL, target)) ? 'extra' : 'behind', note: existsSync(join(NIGHTFALL, target)) ? 'in copy, not in manifest' : 'new file in GameSystems, not copied' });
        seen.add(target);
      }
      for (const rel of walk(dir)) {
        const target = `addons/${name}/${rel}`;
        if (ignore(rel) || seen.has(target) || rel === 'LICENSE') continue;
        entries.push({ file: target, state: 'extra', note: 'in copy, not in manifest or GameSystems' });
      }
    }
    const note = m.dirty ? 'manifest says dirty=true (source had uncommitted changes at sync)' : null;
    addUnit('nightfall-godot', name, entries, { stamp: (m.commit ?? '').slice(0, 8), note, localAdaptationNotes: prose });
  }
  const missing = gsAddons.filter(n => !copies.includes(n));
  info('nightfall-godot', 'not-vendored', 'info', missing.length ? `GameSystems addons without a copy: ${missing.join(', ')}` : 'every GameSystems gs_* addon has a copy');
} else info('nightfall-godot', '-', 'missing', `${NIGHTFALL}/addons not found`);

// ---- Report -------------------------------------------------------------------------------------------------------------
const pad = (s, n) => String(s).padEnd(n);
const rows = units.map(u => [u.project, u.name, u.files, u.equal, u.crlfOnly, u.drift, u.status + (u.stampBehind ? ' (stamp)' : '')]);
if (!flag('--quiet')) {
  console.log(`check_sync (read-only) GameSystems HEAD ${headShort}`);
  const head = ['project', 'unit', 'files', 'equal', 'crlf', 'drift', 'status'];
  const w = head.map((h, i) => Math.max(h.length, ...rows.map(r => String(r[i]).length)));
  console.log(head.map((h, i) => pad(h, w[i])).join('  '));
  for (const r of rows) console.log(r.map((c, i) => pad(c, w[i])).join('  '));
  for (const u of units) {
    const bad = u.entries.filter(e => !['crlf-only'].includes(e.state));
    if (!bad.length && !u.stampBehind && !(u.localAdaptationNotes ?? []).length) continue;
    console.log(`\n[${u.status}] ${u.project}/${u.name}${u.baselineReason ? ` - baseline: ${u.baselineReason}` : ''}`);
    for (const n of u.localAdaptationNotes ?? []) console.log(`  declared local adaptation: ${n}`);
    if (u.stampBehind) console.log(`  stamp: SYNCED.json says ${u.stamp}, GameSystems HEAD is ${u.headStamp}${u.extensionCommitsSinceStamp != null ? `; ${u.extensionCommitsSinceStamp} commit(s) touched this extension since` : ''}`);
    for (const e of bad) console.log(`  ${pad(e.state, 11)} ${e.file}${e.note ? `  (${e.note})` : ''}`);
  }
  console.log('');
  for (const i of infoUnits) console.log(`[${i.status}] ${i.project}/${i.name}: ${i.note}`);
}
const unexpected = units.filter(u => u.status === 'DRIFT').length + infoUnits.filter(i => i.status === 'missing').length;
const known = units.filter(u => u.status === 'KNOWN-DRIFT').length;
const summary = { units: units.length, synced: units.filter(u => u.status === 'SYNCED').length, knownDrift: known, unexpectedDrift: unexpected,
  stampOnly: units.filter(u => u.status === 'SYNCED' && u.stampBehind).length };
console.log(`\nsummary: ${summary.units} units, ${summary.synced} synced (${summary.stampOnly} with an outdated SYNCED.json commit stamp only), ${known} known drift, ${unexpected} UNEXPECTED drift -> exit ${unexpected ? 1 : 0}`);
if (jsonOut) writeFileSync(resolve(jsonOut), JSON.stringify({ generated: new Date().toISOString(), gameSystemsHead: headShort, summary, units, info: infoUnits }, null, 2) + '\n');
process.exit(unexpected ? 1 : 0);
